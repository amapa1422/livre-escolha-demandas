CREATE TABLE usuarios (
  id uuid PRIMARY KEY,
  nome varchar(80) NOT NULL,
  email varchar(254) NOT NULL UNIQUE,
  senha_hash text NOT NULL,
  papel text NOT NULL DEFAULT 'funcionario' CHECK (papel IN ('admin','funcionario')),
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE clientes (
  id uuid PRIMARY KEY,
  nome varchar(100) NOT NULL,
  nome_normalizado varchar(150) NOT NULL,
  logo_path text,
  arquivo_original text,
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX clientes_nome_idx ON clientes (nome_normalizado);
CREATE TABLE demandas (
  id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1041) PRIMARY KEY,
  client varchar(100) NOT NULL,
  cliente_id uuid REFERENCES clientes(id),
  category text NOT NULL CHECK (category IN ('CANCELAMENTO','CONSULTA DE FIDELIDADE','TRANSFERÊNCIA DE TITULARIDADE','MUDANÇA')),
  requester varchar(80) NOT NULL,
  priority text NOT NULL CHECK (priority IN ('Normal','Alta')),
  description varchar(2500) NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente','andamento','lancada')),
  assignee varchar(80) NOT NULL DEFAULT '',
  created timestamptz NOT NULL DEFAULT now(),
  criado_por uuid NOT NULL REFERENCES usuarios(id),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  excluido_em timestamptz,
  version integer NOT NULL DEFAULT 1 CHECK (version > 0),
  chave_criacao uuid NOT NULL,
  UNIQUE (criado_por, chave_criacao)
);
CREATE INDEX demandas_ativas_idx ON demandas (created DESC) WHERE excluido_em IS NULL;
CREATE TABLE anexos (
  id uuid PRIMARY KEY,
  demanda_id integer NOT NULL UNIQUE REFERENCES demandas(id),
  nome_original varchar(255) NOT NULL,
  original_path text NOT NULL,
  arquivo_path text NOT NULL,
  mime text NOT NULL CHECK (mime IN ('image/png','image/jpeg','image/webp')),
  bytes integer NOT NULL CHECK (bytes > 0),
  largura integer NOT NULL,
  altura integer NOT NULL,
  sha256 char(64) NOT NULL,
  criado_em timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE historico (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  demanda_id integer NOT NULL REFERENCES demandas(id),
  usuario_id uuid NOT NULL REFERENCES usuarios(id),
  acao text NOT NULL CHECK (acao IN ('criar','assumir','finalizar','excluir')),
  antes jsonb,
  depois jsonb,
  criado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX historico_demanda_idx ON historico(demanda_id, id);
CREATE TABLE sessoes (
  sid varchar PRIMARY KEY,
  sess json NOT NULL,
  expire timestamp(6) NOT NULL
);
CREATE INDEX sessoes_expire_idx ON sessoes(expire);
